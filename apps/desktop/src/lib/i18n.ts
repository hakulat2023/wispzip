// Lightweight i18n: Chinese/English dictionaries, follows the system language by default, overridable in settings.
// t() reads the locale reactively at render time, so switching the language refreshes all UI text immediately.
import { computed, ref, watchEffect } from "vue";

export type Locale = "zh" | "en";
export type LocaleSetting = Locale | "system";

const STORE_KEY = "wispzip.locale";

function loadSetting(): LocaleSetting {
  const v = localStorage.getItem(STORE_KEY);
  return v === "zh" || v === "en" ? v : "system";
}

function systemLocale(): Locale {
  return /^zh/i.test(navigator.language || "") ? "zh" : "en";
}

const setting = ref<LocaleSetting>(loadSetting());
const locale = computed<Locale>(() => (setting.value === "system" ? systemLocale() : setting.value));

watchEffect(() => {
  document.documentElement.lang = locale.value === "zh" ? "zh-CN" : "en";
});

export function setLocale(v: LocaleSetting) {
  setting.value = v;
  localStorage.setItem(STORE_KEY, v);
}
export function getLocaleSetting(): LocaleSetting {
  return setting.value;
}
export function currentLocale(): Locale {
  return locale.value;
}

